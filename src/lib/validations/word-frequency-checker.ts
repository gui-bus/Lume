export interface RepeatedWordResult {
  word: string;
  count: number;
  locations: string[];
}

export function checkWordFrequency(
  data: ResumeData,
  locale: string = "pt",
): RepeatedWordResult[] {
  const wordsMap: Record<
    string,
    { count: number; locations: Record<string, boolean> }
  > = {};
  const stopwords = locale === "en" ? stopwordsEN : stopwordsPT;

  const extractWords = (text: string | undefined, locationLabel: string) => {
    if (!text) return;

    const cleaned = text
      .toLowerCase()
      .replace(/[.,\/#!$%\^&\*;:{}=\-_`~()?"'\n]/g, " ")
      .replace(/\s+/g, " ");

    const words = cleaned.split(" ");

    words.forEach((word) => {
      const trimmed = word.trim();
      if (trimmed.length < 3) return;
      if (stopwords.has(trimmed)) return;
      if (!isNaN(Number(trimmed))) return;

      if (!wordsMap[trimmed]) {
        wordsMap[trimmed] = { count: 0, locations: {} };
      }
      wordsMap[trimmed].count++;
      wordsMap[trimmed].locations[locationLabel] = true;
    });
  };

  if (data.personalInfo?.summary) {
    extractWords(
      data.personalInfo.summary,
      locale === "en" ? "Summary" : "Resumo",
    );
  }

  data.experiences?.forEach((exp, i) => {
    const label = `${locale === "en" ? "Experience" : "Experiência"} ${i + 1} (${exp.company})`;
    extractWords(exp.position, label);
    extractWords(exp.description, label);
  });

  data.projects?.forEach((proj, i) => {
    const label = `${locale === "en" ? "Project" : "Projeto"} ${i + 1} (${proj.name})`;
    extractWords(proj.description, label);
  });

  data.volunteering?.forEach((vol, i) => {
    const label = `${locale === "en" ? "Volunteer" : "Voluntariado"} ${i + 1} (${vol.organization})`;
    extractWords(vol.role, label);
    extractWords(vol.description, label);
  });

  data.customSections?.forEach((sec) => {
    sec.items.forEach((item, i) => {
      const label = `${sec.title} - ${locale === "en" ? "Item" : "Item"} ${i + 1}`;
      extractWords(item.title, label);
      extractWords(item.description, label);
    });
  });

  const limit = 4;

  const repeated = Object.entries(wordsMap)
    .filter(([_, data]) => data.count >= limit)
    .map(([word, data]) => ({
      word,
      count: data.count,
      locations: Object.keys(data.locations),
    }))
    .sort((a, b) => b.count - a.count);

  return repeated;
}
